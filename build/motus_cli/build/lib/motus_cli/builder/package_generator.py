"""
package_generator.py

Scaffolds a new Motus project workspace and its thin <name>_motus ROS2
package. This is the first stage of the Motus Builder pipeline and is
what `motus create project <name>` calls directly.

Deliberately does NOT touch robot description content -- if a source
robot description is supplied (via `--from`), this module leaves
urdf/config population to the next pipeline stages
(robot_description_import.py / urdf_parser.py / ... / config_generator.py,
not yet written) and only writes a placeholder config/robot.yaml so the
package is a valid, buildable (if not yet meaningful) ROS2 package from
the moment `motus create project` returns.
"""

from __future__ import annotations

import json
import os
import re
from dataclasses import dataclass
from pathlib import Path

from . import templates


@dataclass
class ProjectPaths:
    workspace_root: Path
    src_dir: Path
    pkg_dir: Path
    pkg_name: str
    robot_name: str


def _slugify_package_name(robot_name: str) -> str:
    """'my robot!' -> 'my_robot_motus'. Package names must be valid
    Python identifiers usable as a ROS2 package name (lowercase,
    underscores, no leading digit)."""
    slug = re.sub(r"[^a-zA-Z0-9]+", "_", robot_name.strip()).strip("_").lower()
    if not slug:
        raise ValueError(f"robot name {robot_name!r} has no usable characters")
    if slug[0].isdigit():
        slug = f"r_{slug}"
    return f"{slug}_motus"


def _write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def create_project(
    robot_name: str,
    dest: str | os.PathLike = ".",
    from_path: str | None = None,
    maintainer: str = "you",
) -> ProjectPaths:
    """
    Scaffold <dest>/<robot_name>/ as a Motus project workspace containing
    src/<pkg_name>/ as a buildable ament_python package.

    `from_path`, if given, is recorded in the manifest now so later
    pipeline stages know what to import, but is NOT processed here --
    call the (forthcoming) robot_add() pipeline entry point afterwards
    to actually populate urdf/config from it. Keeping this function
    side-effect-free w.r.t. the source description makes `motus create
    project` safe to re-run/inspect without re-triggering the (more
    expensive, less idempotent) import step.
    """
    pkg_name = _slugify_package_name(robot_name)
    workspace_root = Path(dest) / robot_name
    src_dir = workspace_root / "src"
    pkg_dir = src_dir / pkg_name

    if pkg_dir.exists():
        raise FileExistsError(
            f"{pkg_dir} already exists -- refusing to overwrite an existing "
            f"project. Use `motus robot add <path>` to update robot description "
            f"content in place instead."
        )

    launch_filename = f"{robot_name}.launch.py"
    urdf_filename = f"{robot_name}.urdf.xacro"

    # --- package skeleton ---
    _write(pkg_dir / "package.xml", templates.PACKAGE_XML.format(
        pkg_name=pkg_name, robot_name=robot_name, maintainer=maintainer))
    _write(pkg_dir / "setup.py", templates.SETUP_PY.format(
        pkg_name=pkg_name, robot_name=robot_name, maintainer=maintainer))
    _write(pkg_dir / "resource" / pkg_name, "")
    _write(pkg_dir / pkg_name / "__init__.py", "")

    # --- directories the Builder's later stages populate ---
    # NOTE: meshes/ is a SIBLING of urdf/, not nested under it -- this must
    # match both robokpy_controller's own built-in layout and the mesh
    # path arm.launch.py's override branch resolves
    # (FindPackageShare(mesh_package_name) + 'meshes'). Keep these three
    # in sync if either changes.
    (pkg_dir / "urdf").mkdir(parents=True, exist_ok=True)
    (pkg_dir / "meshes").mkdir(parents=True, exist_ok=True)
    (pkg_dir / "rviz").mkdir(parents=True, exist_ok=True)

    # Placeholder URDF so the package is at least parseable before
    # `motus robot add` runs. Not a real robot -- one fixed link, flagged
    # by `motus doctor` as "no robot description imported yet".
    _write(pkg_dir / "urdf" / urdf_filename, (
        "<?xml version=\"1.0\"?>\n"
        f"<robot name=\"{pkg_name}\">\n"
        "  <!-- Placeholder: no robot description imported yet.\n"
        "       Run `motus robot add <path-to-description>` from this\n"
        "       project's root to replace this file. -->\n"
        "  <link name=\"base_link\"/>\n"
        "</robot>\n"
    ))

    _write(pkg_dir / "config" / "robot.yaml", templates.ROBOT_YAML_STUB)
    _write(pkg_dir / "config" / "controllers.yaml", (
        "# Generated by Motus Builder -- placeholder until `motus robot add`\n"
        "# populates this from the imported robot's joint list.\n"
        "controller_manager:\n"
        "  ros__parameters:\n"
        "    update_rate: 100\n"
    ))

    _write(pkg_dir / "launch" / launch_filename, templates.LAUNCH_WRAPPER.format(
        launch_name=launch_filename, robot_name=robot_name, pkg_name=pkg_name,
        urdf_filename=urdf_filename,
    ))

    # --- workspace-level files ---
    _write(workspace_root / "README.md", templates.README.format(
        robot_name=robot_name, pkg_name=pkg_name, launch_name=launch_filename))
    _write(workspace_root / "motus.json", templates.MANIFEST_JSON.format(
        robot_name=robot_name, pkg_name=pkg_name,
        source_description_path_json=json.dumps(from_path),
        parent_workspace_root_json=json.dumps(os.path.abspath(os.getcwd())),
    ))

    return ProjectPaths(
        workspace_root=workspace_root, src_dir=src_dir, pkg_dir=pkg_dir,
        pkg_name=pkg_name, robot_name=robot_name,
    )


def update_manifest_fingerprint(workspace_root: Path, fingerprint: str) -> None:
    """Called by later build stages (not this one) once a real build/
    validation pass has completed, to record what state was last checked."""
    manifest_path = workspace_root / "motus.json"
    data = json.loads(manifest_path.read_text(encoding="utf-8"))
    data["last_build_fingerprint"] = fingerprint
    manifest_path.write_text(json.dumps(data, indent=2), encoding="utf-8")